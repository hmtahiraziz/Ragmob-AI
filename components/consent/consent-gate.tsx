import { useRouter, useSegments } from 'expo-router';
import { useState } from 'react';
import { Modal, Pressable, ScrollView, StyleSheet, Text, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';

import { Button, Spinner } from '@/components/ui';
import { Radius, Spacing, Typography } from '@/constants/theme';
import { useConsent } from '@/hooks/use-consent';
import { useTheme } from '@/hooks/use-theme';
import { CONSENT_VERSION } from '@/lib/storage/consent';

type ConsentGateProps = {
  /** When false, skip the gate (signed-out flows). */
  enabled: boolean;
  children: React.ReactNode;
};

export function ConsentGate({ enabled, children }: ConsentGateProps) {
  const { colors } = useTheme();
  const insets = useSafeAreaInsets();
  const router = useRouter();
  const segments = useSegments();
  const { hydrated, accepted, accept } = useConsent();
  const [busy, setBusy] = useState(false);
  const viewingLegal =
    segments[0] === 'privacy-policy' || segments[0] === 'terms-of-service';

  if (!enabled) return <>{children}</>;
  if (!hydrated) {
    return (
      <View style={[styles.loading, { backgroundColor: colors.background }]}>
        <Spinner centered label="Loading…" />
      </View>
    );
  }

  const needsConsent = !accepted;

  const handleAccept = async () => {
    if (busy) return;
    setBusy(true);
    try {
      await accept();
    } finally {
      setBusy(false);
    }
  };

  return (
    <>
      {children}
      <Modal
        visible={needsConsent && !viewingLegal}
        animationType="slide"
        presentationStyle="fullScreen">
        <View
          style={[
            styles.screen,
            {
              backgroundColor: colors.background,
              paddingTop: insets.top + Spacing.lg,
              paddingBottom: insets.bottom + Spacing.lg,
            },
          ]}>
          <ScrollView
            contentContainerStyle={styles.body}
            showsVerticalScrollIndicator={false}>
            <Text style={[Typography.display, { color: colors.text }]}>Before you chat</Text>
            <Text style={[Typography.body, styles.lead, { color: colors.textSecondary }]}>
              Ragmob is an AI chat assistant. Please review how your data is used.
            </Text>

            <View style={[styles.card, { backgroundColor: colors.surface }]}>
              <Text style={[Typography.label, styles.cardTitle, { color: colors.textMuted }]}>
                Important notice
              </Text>
              <Text style={[Typography.body, { color: colors.text, lineHeight: 22 }]}>
                Responses are generated by artificial intelligence and can be wrong or incomplete.
                Do not rely on Ragmob for medical, legal, financial, or other professional advice.
              </Text>
            </View>

            <View style={[styles.card, { backgroundColor: colors.surface }]}>
              <Text style={[Typography.label, styles.cardTitle, { color: colors.textMuted }]}>
                Data we process
              </Text>
              <Text style={[Typography.body, { color: colors.text, lineHeight: 22 }]}>
                Your prompts and replies are sent to our servers and AI model provider to generate
                answers. Account details (email, name, avatar) are managed by Clerk. Chats may be
                stored so you can continue conversations. We do not sell your data or use ads/ad IDs.
              </Text>
            </View>

            <Text style={[Typography.caption, { color: colors.textMuted }]}>
              By continuing you agree to this notice, our Terms of Service, and our privacy policy.
              You can delete chats or your account anytime in Settings. Consent version{' '}
              {CONSENT_VERSION}.
            </Text>

            <Pressable
              onPress={() => router.push('/terms-of-service')}
              hitSlop={8}
              accessibilityRole="link"
              style={styles.linkHit}>
              <Text style={[Typography.body, styles.link, { color: colors.primaryDark }]}>
                Read Terms of Service
              </Text>
            </Pressable>

            <Pressable
              onPress={() => router.push('/privacy-policy')}
              hitSlop={8}
              accessibilityRole="link"
              style={styles.linkHit}>
              <Text style={[Typography.body, styles.link, { color: colors.primaryDark }]}>
                Read privacy policy
              </Text>
            </Pressable>
          </ScrollView>

          <View style={styles.footer}>
            <Button
              title="I agree — continue"
              size="lg"
              fullWidth
              loading={busy}
              onPress={handleAccept}
            />
          </View>
        </View>
      </Modal>
    </>
  );
}

const styles = StyleSheet.create({
  loading: { flex: 1 },
  screen: { flex: 1, paddingHorizontal: Spacing.lg },
  body: { gap: Spacing.md, paddingBottom: Spacing.xl },
  lead: { marginTop: Spacing.xs },
  card: {
    borderRadius: Radius.lg,
    padding: Spacing.lg,
    gap: Spacing.sm,
  },
  cardTitle: {
    textTransform: 'uppercase',
    letterSpacing: 0.4,
  },
  link: { fontWeight: '600' },
  linkHit: { minHeight: 48, justifyContent: 'center' },
  footer: { paddingTop: Spacing.md },
});
